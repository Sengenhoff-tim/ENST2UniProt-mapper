use crate::uniprot::UniProtEntry;
use crate::variant::Variant;

use super::comment::alternative_products_cc;
use super::feature::var_seq_ft_lines;
use super::sequence::format_seq_body;

/// Build the synthetic Swiss-Prot-style flat file entry text.
/// `accession` is the UniProt accession, or the ENST id for synthetic Ensembl
/// entries; `entry` is `Some` for UniProt-backed entries, `None` otherwise.
pub(crate) fn format_entry(
    accession: &str,
    sequence: &str,
    variants: &[Variant],
    entry: Option<&UniProtEntry>,
) -> String {
    let date = "01-JAN-1970";

    let (protein_desc, gene) = match entry {
        Some(e) => (e.protein_name().to_string(), e.gene_name().to_string()),
        None => (accession.to_string(), accession.to_string()),
    };

    let id_ac = format!(
        "ID   {:<24}Reviewed;         {} AA.\nAC   {};",
        accession,
        sequence.len(),
        accession
    );

    let mut ft_lines: Vec<String> = Vec::new();

    // VAR_SEQ features
    if let Some(entry) = entry {
        for feature in entry.var_seq_features() {
            if let Some(var_seq) = var_seq_ft_lines(feature, entry) {
                ft_lines.extend(var_seq);
            }
        }
    }

    // VARIANT features
    for variant in variants {
        ft_lines.extend(variant.ft_lines());
    }

    let ft_block = if ft_lines.is_empty() {
        String::new()
    } else {
        format!("\n{}", ft_lines.join("\n"))
    };

    let cc_alt_products = entry
        .and_then(|e| e.alternative_products.as_ref())
        .map(|ap| format!("{}\n", alternative_products_cc(ap)))
        .unwrap_or_default();

    let sq_line = format!(
        "SQ   SEQUENCE   {} AA;  0 MW;  0000000000000000 CRC64;",
        sequence.len()
    );
    let seq_body = format_seq_body(sequence);
    let acc = accession;

    format!(
        "{id_ac}
DT   {date}, integrated into UTA.
DT   {date}, sequence version 1.
DT   {date}, entry version 1.
DE   RecName: Full={protein_desc};
GN   Name={gene}; Synonyms={gene}; ORFNames={gene};
OS   Autogenerated.
OC   Autogenerated.
OX   NCBI_TaxID=0000;
RN   [1]
RP   AUTOGENERATED
RA   This file was autogenerated;
RT   \"This is an autogenerated file.\";
RL   (er) Autogenerated.
CC   -!- CAUTION: This file was autogenerated and sequences
CC       can differ from UniProt!
{cc_alt_products}DR   UTA; {acc}; Universal Transcript Archive
PE   4: Predicted;
KW   Generated for ProtGraph{ft_block}
{sq_line}
{seq_body}
//"
    )
}

